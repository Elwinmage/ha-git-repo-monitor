const LANGS: Record<string, Dict> = { en, fr, de, es, it, pl, pt };

export function translator(language: string | undefined): (key: string) => string {
  const dict = LANGS[(language || "en").split("-")[0]] || en;
  return (key: string) => dict[key] ?? en[key] ?? key;
}
